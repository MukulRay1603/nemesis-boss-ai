"""
Regenerate the results tables on the web page and in the README from eval/unity.

Reads every <label>_<preset>_s<seed>_episodes.csv, pools seeds, and rewrites the block between
  <!-- RESULTS:START --> and <!-- RESULTS:END -->
in README.md (markdown) and Unity Project/Assets/WebGLTemplates/Nemesis/index.html (table rows).
Only numbers measured in eval/unity are written. Standard library only.

Usage:
    python eval/update_results.py            # rewrite both files
    python eval/update_results.py --print    # just print the markdown table
"""

import csv
import glob
import math
import os
import re
import sys
from collections import defaultdict

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EVAL = os.path.join(REPO, "eval", "unity")
README = os.path.join(REPO, "README.md")
PAGE = os.path.join(REPO, "Unity Project", "Assets", "WebGLTemplates", "Nemesis", "index.html")

NAMES = {
    "v5": "Retrained PPO policy, adaptive (v5)",
    "v4": "Retrained PPO policy (v4)",
    "v3": "Original PPO policy (v3)",
    "attack": "Same boss, always attack",
    "random": "Same boss, random move",
    "fsm": "Scripted boss, no wind-up or recovery",
}
ORDER = ["v5", "v4", "v3", "attack", "random", "fsm"]


def wilson(k, n, z=1.96):
    if n == 0:
        return 0.0, 0.0
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return c - h, c + h


def collect():
    data = defaultdict(lambda: defaultdict(list))   # label -> preset -> episodes
    for path in glob.glob(os.path.join(EVAL, "*_episodes.csv")):
        m = re.match(r"(.+)_(default|hard)_s\d+_episodes\.csv$", os.path.basename(path))
        if not m:
            continue
        with open(path) as f:
            data[m.group(1)][m.group(2)] += list(csv.DictReader(f))
    return data


def cell(eps):
    if not eps:
        return "n/a", None
    n = len(eps)
    k = sum(e["outcome"] == "BOSS_WIN" for e in eps)
    lo, hi = wilson(k, n)
    dur = sum(float(e["duration_s"]) for e in eps) / n
    return f"{k / n:.1%}", (n, lo, hi, dur)


def rows(data):
    out = []
    for label in ORDER:
        if label not in data:
            continue
        d, dinfo = cell(data[label]["default"])
        h, hinfo = cell(data[label]["hard"])
        out.append((label, NAMES[label], d, dinfo, h, hinfo))
    return out


def markdown(rs):
    lines = ["| Boss | vs default bot | vs hard bot |", "|---|---|---|"]
    for label, name, d, di, h, hi in rs:
        fmt = lambda v, i: f"{v} ({i[1]:.1%} to {i[2]:.1%}), {i[3]:.0f} s avg" if i else v
        lines.append(f"| {name} | {fmt(d, di)} | {fmt(h, hi)} |")
    n = next((i[0] for _, _, _, i, _, _ in rs if i), 0)
    lines.append("")
    lines.append(f"Boss win rate with 95% Wilson interval and mean fight length. {n} fights per cell "
                 f"(3 seeds x 200), fights capped at 90 s. Generated by eval/update_results.py from eval/unity/.")
    return "\n".join(lines)


def html(rs):
    best = None
    lines = []
    for label, name, d, di, h, hi in rs:
        cls = ' class="hl"' if label in ("v5", "v4", "v3") and best is None else ""
        if cls:
            best = label
        lines.append(f'            <tr{cls}><td>{name}</td><td class="num">{d}</td><td class="num">{h}</td></tr>')
    return "\n".join(lines)


def replace_block(path, new, indent=""):
    with open(path, encoding="utf-8") as f:
        s = f.read()
    pat = re.compile(r"(<!-- RESULTS:START -->)(.*?)(\s*<!-- RESULTS:END -->)", re.S)
    if not pat.search(s):
        print(f"no RESULTS markers in {path}, skipped")
        return
    s = pat.sub(lambda m: m.group(1) + "\n" + new + "\n" + indent + m.group(3).lstrip("\n").lstrip(), s)
    with open(path, "w", encoding="utf-8") as f:
        f.write(s)
    print(f"updated {os.path.relpath(path, REPO)}")


def main():
    rs = rows(collect())
    md = markdown(rs)
    if "--print" in sys.argv:
        print(md)
        return
    replace_block(README, md)
    replace_block(PAGE, html(rs), "            ")


if __name__ == "__main__":
    main()
